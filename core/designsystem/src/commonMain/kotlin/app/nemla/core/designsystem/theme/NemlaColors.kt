internal fun NemlaColors.toColorScheme(): ColorScheme {
    val primaryContainer = primary.copy(alpha = 0.10f).compositeOver(background)
    val tertiaryContainer = accent.copy(alpha = 0.20f).compositeOver(background)
    val errorContainer = destructive.copy(alpha = 0.10f).compositeOver(background)
    return if (isDark) {
        darkColorScheme(
            primary = primary,
            onPrimary = primaryForeground,
            primaryContainer = primaryContainer,
            onPrimaryContainer = primary,
            inversePrimary = LightNemlaColors.primary,
            secondary = secondaryForeground,
            onSecondary = secondary,
            secondaryContainer = selectedContainer,
            onSecondaryContainer = onSelectedContainer,
            tertiary = accent,
            onTertiary = accentForeground,
            tertiaryContainer = tertiaryContainer,
            onTertiaryContainer = accentForeground,
            background = background,
            onBackground = foreground,
            surface = background,
            onSurface = foreground,
            surfaceVariant = muted,
            onSurfaceVariant = mutedForeground,
            surfaceTint = Color.Transparent,
            inverseSurface = foreground,
            inverseOnSurface = background,
            surfaceContainerLowest = Color(0xFF0A110D),
            surfaceContainerLow = card,
            surfaceContainer = Color(0xFF1B271F),
            surfaceContainerHigh = Color(0xFF202C24),
            surfaceContainerHighest = Color(0xFF29372E),
            surfaceDim = background,
            surfaceBright = Color(0xFF29372E),
            outline = input,
            outlineVariant = border,
            error = destructive,
            onError = destructiveForeground,
            errorContainer = errorContainer,
            onErrorContainer = destructive,
            scrim = Color.Black,
        )
    } else {
        lightColorScheme(
            primary = primary,
            onPrimary = primaryForeground,
            primaryContainer = primaryContainer,
            onPrimaryContainer = primary,
            inversePrimary = DarkNemlaColors.primary,
            secondary = secondaryForeground,
            onSecondary = secondary,
            secondaryContainer = Color(0xFFDCE7D0),
            onSecondaryContainer = secondaryForeground,
            tertiary = accent,
            onTertiary = accentForeground,
            tertiaryContainer = tertiaryContainer,
            onTertiaryContainer = accentForeground,
            background = background,
            onBackground = foreground,
            surface = background,
            onSurface = foreground,
            surfaceVariant = muted,
            onSurfaceVariant = mutedForeground,
            surfaceTint = Color.Transparent,
            inverseSurface = foreground,
            inverseOnSurface = background,
            surfaceContainerLowest = card,
            surfaceContainerLow = Color(0xFFF7F5EB),
            surfaceContainer = muted,
            surfaceContainerHigh = Color(0xFFEEEBE0),
            surfaceContainerHighest = Color(0xFFE8E5DA),
            surfaceDim = Color(0xFFE8E5DA),
            surfaceBright = card,
            outline = input,
            outlineVariant = border,
            error = destructive,
            onError = destructiveForeground,
            errorContainer = errorContainer,
            onErrorContainer = destructive,
            scrim = Color.Black,
        )
    }
}
